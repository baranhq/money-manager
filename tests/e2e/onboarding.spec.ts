  const entry = page.getByRole("dialog", { name: "New entry" })
  await expect(entry.getByRole("tab", { name: "Income" })).toHaveAttribute("aria-selected", "true")
  await expect(entry.getByRole("complementary", { name: "App tour" })).toContainText("Enter the amount and pick a category.")
  await expect(next).toBeDisabled()
  await page.screenshot({ path: info.outputPath("tour-entry-dark-320.png") })
  await entry.getByRole("textbox", { name: "Amount" }).fill("25.50")
  await entry.getByRole("textbox", { name: "Income description" }).fill("Weekend work")
