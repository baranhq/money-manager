import { expect, test } from "@playwright/test"
import { initialData, today } from "../../src/lib/finance.ts"

test("mobile setup retains currency and account drafts through a refresh", async ({ page }, info) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.emulateMedia({ colorScheme: "dark" })
  const externalRequests: string[] = []
  page.on("request", request => {
    if (!request.url().startsWith("http://127.0.0.1:3210/") || request.method() !== "GET") externalRequests.push(request.url())
  })
  await page.goto("/")
  await expect(page.getByRole("heading", { name: "Hello, money." })).toBeFocused()
  const dialogue = page.getByRole("dialog", { name: "Hello, money." })
  await expect(dialogue).toHaveCSS("width", "320px")
  await expect(dialogue).toHaveCSS("height", "740px")
  await expect(page.getByRole("button", { name: "EUR — Euro" })).toHaveAttribute("aria-pressed", "true")
  await page.getByRole("combobox", { name: "See all currencies" }).click()
  const list = await page.getByRole("listbox").boundingBox()
  if (!list) throw new Error("The currency list was not visible.")
  expect(list.x).toBeGreaterThanOrEqual(0)
  expect(list.x + list.width).toBeLessThanOrEqual(320)
  await page.getByRole("option", { name: "JPY — Japanese Yen" }).click()
  await expect(page.getByRole("status").filter({ hasText: "JPY — Japanese Yen" })).toBeVisible()
  const usd = page.getByRole("button", { name: "USD — US Dollar" })
  await usd.focus()
  await page.keyboard.press("Space")
  await expect(usd).toHaveAttribute("aria-pressed", "true")
  expect(await usd.evaluate(button => getComputedStyle(button).transitionDuration)).toBe("0s")
  await expect(dialogue.getByText("Locale and appearance")).toHaveCount(0)
  await expect(page.locator("html")).toHaveClass(/dark/)
  await page.getByRole("button", { name: "Add an account", exact: true }).click()
  await expect(page.getByRole("button", { name: "Cash", exact: true })).toBeFocused()
  await page.getByRole("button", { name: "Add account", exact: true }).click()
  await expect(page.getByText("Cash", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Remove Cash" }).click()
  await page.getByRole("button", { name: "Add an account", exact: true }).click()
  await page.getByRole("button", { name: "Bank", exact: true }).click()
  const name = page.getByRole("textbox", { name: "Account name" })
  const balance = page.getByRole("textbox", { name: "Opening balance (optional)" })
  await expect(name).toHaveValue("Bank account")
  await name.fill("")
  await page.getByRole("button", { name: "Add account", exact: true }).click()
  await expect(name).toBeFocused()
  await expect(name).toHaveAccessibleDescription("Enter an account name.")
  await name.fill("Everyday account")
  await page.getByRole("button", { name: "Add an opening balance", exact: true }).click()
  await expect(balance).toBeFocused()
  await balance.fill("-45.50")
  await expect.poll(() => page.evaluate(() => new Promise(resolve => {
    const database = indexedDB.open("money-manager")
    database.onsuccess = () => {
      const db = database.result
      const request = db.transaction("snapshots").objectStore("snapshots").get("first-time-setup")
      request.onsuccess = () => { resolve(request.result?.editor?.balance); db.close() }
      request.onerror = () => { resolve(null); db.close() }
    }
    database.onerror = () => resolve(null)
  }))).toBe("-45.50")
  await page.reload()
  await expect(name).toHaveValue("Everyday account")
  await expect(balance).toHaveValue("-45.50")
  await expect(page.locator("html")).toHaveClass(/dark/)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
  await page.screenshot({ path: info.outputPath("onboarding-dark-320.png") })
  await page.getByRole("button", { name: "Add account", exact: true }).click()
  await expect(usd).toHaveAttribute("aria-pressed", "true")
  await page.getByRole("button", { name: "Start tracking", exact: true }).click()
  await page.getByRole("button", { name: "Skip tour", exact: true }).click()
  await page.getByRole("navigation", { name: "Mobile navigation" }).getByRole("button", { name: "Add", exact: true }).click()
  await page.getByRole("dialog", { name: "Add entry" }).getByRole("button", { name: "Expense", exact: true }).click()
  await expect(page.getByLabel("Account", { exact: true })).toHaveValue("Everyday account")
  await page.goto("/#ledger-accounts")
  await expect(page.getByRole("heading", { name: "Accounts", exact: true })).toBeVisible()
  await expect(page.getByText(/Bank · Opening balance -(?:US)?\$45\.50/)).toBeVisible()
  await page.getByRole("button", { name: "Edit Everyday account" }).click()
  await page.getByRole("textbox", { name: "Opening balance (optional)" }).fill("15.00")
  await page.getByRole("button", { name: "Save account", exact: true }).click()
  await expect(page.getByText(/Bank · Opening balance (?:US)?\$15\.00/)).toBeVisible()
  expect(externalRequests).toEqual([])
})

test("desktop setup is a keyboard-contained popup and skipping keeps defaults", async ({ page }, info) => {
  await page.setViewportSize({ width: 1200, height: 800 })
  await page.emulateMedia({ reducedMotion: "no-preference" })
  await page.goto("/")
  const step = page.getByRole("heading", { name: "Hello, money." })
  await expect(step).toBeVisible()
  const dialogue = page.getByRole("dialog", { name: "Hello, money." })
  await expect(dialogue).toHaveCSS("width", "480px")
  await expect(page.locator('[data-tour-target="overview"]')).toBeVisible()
  await expect.poll(async () => (await dialogue.boundingBox())?.x).toBe(360)
  const euro = page.getByRole("button", { name: "EUR — Euro" })
  expect(await euro.evaluate(button => getComputedStyle(button).transitionProperty)).toContain("transform")
  await expect(dialogue.getByText("Baran’s Money Manager", { exact: true }).locator("svg")).toHaveCount(0)
  await page.screenshot({ path: info.outputPath("onboarding-light-desktop.png") })
  await page.getByRole("button", { name: "USD — US Dollar" }).click()
  await page.getByRole("button", { name: "Skip setup", exact: true }).focus()
  await page.keyboard.press("Tab")
  expect(await dialogue.evaluate(el => el.contains(document.activeElement))).toBe(true)
  await page.getByRole("button", { name: "Skip setup", exact: true }).press("Enter")
  await expect(page.getByRole("heading", { name: "Overview", exact: true })).toBeVisible()
  await expect(page.getByText("Available to spend", { exact: true })).toBeVisible()
  await expect(page.locator('[data-tour-target="overview"]')).toContainText("€0.00")
  await page.getByRole("button", { name: "Skip tour", exact: true }).click()
  await page.reload()
  await expect(page.getByRole("heading", { name: "Overview", exact: true })).toBeVisible()
  await expect(step).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Take the tour" })).toHaveCount(0)
})

test("the optional tour follows real controls, adapts to the viewport, and can be replayed", async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto("/")
  await page.getByRole("button", { name: "Skip setup", exact: true }).click()
  const spot = page.locator("[data-tour-spotlight]")
  const next = page.getByRole("button", { name: "Next", exact: true })
  await page.getByRole("navigation", { name: "Mobile navigation" }).getByRole("link", { name: "Activity" }).click()
  await expect(page.getByRole("heading", { name: "Activity", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Take the tour", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Your dashboard", exact: true })).toBeFocused()
  await expect(spot).toBeVisible()
  await expect(page.getByRole("button", { name: "Back", exact: true })).toBeDisabled()
  await next.press("Enter")
  await expect(page).toHaveURL(/#activity$/)
  await expect(page.getByRole("dialog", { name: "Log a transaction" })).toBeVisible()
  await expect(page.getByRole("button", { name: "Skip tour", exact: true })).toBeVisible()
  const add = page.getByRole("navigation", { name: "Mobile navigation" }).getByRole("button", { name: "Add", exact: true })
  await expect.poll(async () => Math.abs((await add.boundingBox())!.x - (await spot.boundingBox())!.x)).toBeLessThanOrEqual(5)
  await page.screenshot({ path: info.outputPath("tour-mobile.png") })
  await page.setViewportSize({ width: 320, height: 740 })
  const mobileTip = page.getByRole("dialog", { name: "Log a transaction" })
  await expect.poll(async () => {
    const box = await mobileTip.boundingBox()
    return Boolean(box && box.x >= 0 && box.x + box.width <= 320)
  }).toBe(true)
  await next.click()
  await expect(page).toHaveURL(/#settings$/)
  const accountLink = page.getByRole("link", { name: /^Accounts Manage/ })
  await expect(accountLink).toBeInViewport()
  await expect(spot).toBeVisible()
  await accountLink.evaluate(el => { el.removeAttribute("data-tour-target") })
  await expect(spot).toHaveCount(0)
  await expect(page.getByRole("dialog", { name: "Keep accounts separate" })).toBeVisible()
  await expect(page.getByRole("button", { name: "Skip tour", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Back", exact: true }).click()
  await expect(page).toHaveURL(/#activity$/)
  await page.setViewportSize({ width: 1024, height: 768 })
  const desktopAdd = page.getByRole("button", { name: "Add transaction", exact: true }).first()
  await expect.poll(async () => Math.abs((await desktopAdd.boundingBox())!.x - (await spot.boundingBox())!.x)).toBeLessThanOrEqual(5)
  await page.screenshot({ path: info.outputPath("tour-tablet.png") })
  await next.click()
  await next.click()
  await expect(page).toHaveURL(/#budgets$/)
  await expect(page.getByRole("dialog", { name: "Give spending a limit" })).toBeVisible()
  await next.click()
  await expect(page).toHaveURL(/#savings$/)
  await expect(page.getByRole("dialog", { name: "Set something aside" })).toBeVisible()
  await page.getByRole("button", { name: "Done", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Overview", exact: true })).toBeVisible()
  await expect(page.locator("#main-content")).toBeFocused()
  expect(await page.evaluate(() => localStorage.getItem("money-manager:app-tour"))).toBe("completed")
  await page.goto("/#settings")
  await page.getByRole("button", { name: /^Replay app tour/ }).click()
  await expect(page.getByRole("heading", { name: "Your dashboard", exact: true })).toBeFocused()
  await page.keyboard.press("Escape")
  await expect(page.getByRole("dialog")).toHaveCount(0)
  expect(await page.evaluate(() => localStorage.getItem("money-manager:app-tour"))).toBe("skipped")
  await page.goto("/#settings")
  await page.getByRole("button", { name: /^Replay app tour/ }).click()
  await next.click()
  await expect(page.getByRole("dialog", { name: "Log a transaction" })).toBeVisible()
  await desktopAdd.click()
  await expect(page.getByRole("dialog", { name: "Add entry" })).toBeVisible()
  await expect(page.getByRole("dialog", { name: "Log a transaction" })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole("button", { name: "Take the tour" })).toHaveCount(0)
})

test("older ledgers open without setup and keep their local transaction", async ({ page }) => {
  await page.goto("/privacy")
  const legacy = initialData()
  legacy.entries.push({
    id: "existing-entry", name: "Existing cash expense", amount: 100, kind: "expense", date: today(), category: "dining", account: "Cash", notes: "",
  })
  await page.evaluate(data => new Promise<void>((resolve, reject) => {
    const request = indexedDB.open("money-manager", 1)
    request.onupgradeneeded = () => { request.result.createObjectStore("snapshots") }
    request.onerror = () => reject(request.error)
    request.onsuccess = () => {
      const db = request.result
      const transaction = db.transaction("snapshots", "readwrite")
      transaction.objectStore("snapshots").put(data, "current")
      transaction.oncomplete = () => { db.close(); resolve() }
      transaction.onabort = () => { db.close(); reject(transaction.error) }
    }
  }), legacy)
  await page.goto("/#activity")
  await expect(page.getByRole("heading", { name: "Activity", exact: true })).toBeVisible()
  await expect(page.getByRole("table", { name: "Transactions" }).getByRole("row", { name: /Existing cash expense/ })).toBeVisible()
  await expect(page.getByRole("heading", { name: "Hello, money." })).toHaveCount(0)
})
